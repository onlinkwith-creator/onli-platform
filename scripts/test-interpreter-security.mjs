import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const interpreter = '00000000-0000-0000-0000-000000000002';
const stranger = '00000000-0000-0000-0000-000000000003';
const admin = '00000000-0000-0000-0000-000000000004';

try {
  await db.exec(`
    create role authenticated;
    create schema auth;
    create schema storage;
    create function auth.uid() returns uuid language sql stable as
      $$select nullif(current_setting('test.uid',true),'')::uuid$$;
    create function auth.role() returns text language sql stable as
      $$select current_setting('test.role',true)$$;
    create table auth.users(id uuid primary key,email text);
    create table storage.objects(bucket_id text,name text);
    create function public.is_active_admin() returns boolean language sql stable as
      $$select coalesce(auth.uid()='${admin}'::uuid,false)$$;
    create table public.interpreters(
      id bigint generated by default as identity primary key,
      auth_user_id uuid,email text,name text,status text default 'active',
      approved boolean default false,is_public boolean default true,
      withdrawn_at timestamptz,level text default 'Lv1',warning_count integer default 0,
      admin_memo text,badge_review_status text,resume_verified_email_sent_at timestamptz,
      interpreter_no text,resume_url text,resume_file_url text,resume_file_name text,
      bankbook_file_url text,bankbook_file_name text,
      business_license_file_url text,business_license_file_name text
    );
    insert into auth.users values ('${interpreter}','i@example.test'),
      ('${stranger}','s@example.test'),('${admin}','a@example.test');
    alter table public.interpreters enable row level security;
    create policy own_profile on public.interpreters for all to authenticated
      using(auth_user_id=auth.uid() or public.is_active_admin())
      with check(auth_user_id=auth.uid() or public.is_active_admin());
    grant usage on schema public,auth,storage to authenticated;
    grant select,insert,update on public.interpreters to authenticated;
  `);
  await db.exec(await readFile(new URL('../supabase/migrations/20260926090000_guard_interpreter_self_service.sql',import.meta.url),'utf8'));

  const login = async id => {
    await db.exec('reset role');
    await db.query("select set_config('test.uid',$1,false)",[id]);
    await db.query("select set_config('test.role','authenticated',false)");
    await db.exec('set role authenticated');
  };
  const query = async (sql,params=[]) => (await db.query(sql,params)).rows;
  await login(interpreter);
  await assert.rejects(query(`insert into interpreters(auth_user_id,email,name,status,is_public,approved)
    values ($1,'i@example.test','I','active',true,true)`,[interpreter]));
  await assert.rejects(query(`insert into interpreters(auth_user_id,email,name,status,is_public,approved,level)
    values ($1,'i@example.test','I','pending',false,false,'Lv4')`,[interpreter]));
  await assert.rejects(query(`insert into interpreters(auth_user_id,email,name,status,is_public,approved)
    values ($1,'s@example.test','I','pending',false,false)`,[interpreter]));
  const inserted = await query(`insert into interpreters(auth_user_id,email,name,status,is_public,approved)
    values ($1,'i@example.test','I','pending',false,false) returning id`,[interpreter]);
  const id=inserted[0].id;
  await assert.rejects(query('update interpreters set approved=true where id=$1',[id]));
  await assert.rejects(query("update interpreters set level='Lv4' where id=$1",[id]));
  await assert.rejects(query('update interpreters set is_public=true where id=$1',[id]));
  await assert.rejects(query("update interpreters set status='active' where id=$1",[id]));
  await assert.rejects(query("update interpreters set email='other@example.test' where id=$1",[id]));
  await query("update interpreters set name='Changed' where id=$1",[id]);

  await db.exec('reset role');
  await db.query('insert into storage.objects values($1,$2)',[
    'resume-files',`${interpreter}/resume.pdf`]);
  await db.query('insert into storage.objects values($1,$2)',[
    'resume-files',`interpreter-documents/${interpreter}/settlement/bankbook_1.pdf`]);
  await db.query('insert into storage.objects values($1,$2)',[
    'resume-files',`interpreter-documents/${interpreter}/settlement/business_license_1.pdf`]);
  await login(interpreter);
  await assert.rejects(query("update interpreters set resume_file_url='other/resume.pdf' where id=$1",[id]));
  await query('update interpreters set resume_file_url=$1 where id=$2',[
    `${interpreter}/resume.pdf`,id]);
  await assert.rejects(query('update interpreters set bankbook_file_url=$1 where id=$2',[
    `interpreter-documents/${stranger}/settlement/bankbook_1.pdf`,id]));
  await query('update interpreters set bankbook_file_url=$1 where id=$2',[
    `interpreter-documents/${interpreter}/settlement/bankbook_1.pdf`,id]);
  await query('update interpreters set business_license_file_url=$1 where id=$2',[
    `interpreter-documents/${interpreter}/settlement/business_license_1.pdf`,id]);

  await query("update interpreters set status='withdrawn',is_public=false,withdrawn_at=now() where id=$1",[id]);
  await assert.rejects(query("update interpreters set status='active',is_public=true,withdrawn_at=null where id=$1",[id]));
  await query("update interpreters set status='pending',approved=false,is_public=false,withdrawn_at=null where id=$1",[id]);
  await login(admin);
  await query("update interpreters set status='active',approved=true,is_public=true,level='Lv3' where id=$1",[id]);
  await login(interpreter);
  await query('update interpreters set approved=false where id=$1',[id]);
  await assert.rejects(query('update interpreters set approved=true where id=$1',[id]));
  await login(stranger);
  assert.equal((await query('select * from interpreters where id=$1',[id])).length,0);
  console.log('PASS: interpreter registration fields, self-update boundaries, withdrawal/reactivation, owned document paths');
} finally {
  await db.close();
}
